import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { cities } = require("world-cities-json");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationPath = resolve(root, "supabase/migrations/20261013151000_seed_supported_uk_cities.sql");

if (!Array.isArray(cities)) throw new Error("world-cities-json did not export a city list.");

const ukCities = cities
  .filter((city) => city.iso2 === "GB" && /^\d{10}$/.test(String(city.id)))
  .map((city) => ({
    cityId: `GB-${city.id}`,
    cityName: String(city.city).trim(),
    cityAscii: String(city.city_ascii || city.city).trim(),
    adminName: String(city.admin_name || "").trim(),
    latitude: Number(city.lat),
    longitude: Number(city.lng),
    population: Math.max(0, Number.parseInt(city.population, 10) || 0),
  }))
  .sort((first, second) => first.cityName.localeCompare(second.cityName, "en-GB") || first.cityId.localeCompare(second.cityId));

if (ukCities.length < 1000 || new Set(ukCities.map((city) => city.cityId)).size !== ukCities.length) {
  throw new Error(`Unexpected UK city data: ${ukCities.length} entries.`);
}

const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const numberOrNull = (value) => Number.isFinite(value) ? String(value) : "null";
const valueRows = ukCities.map((city) => `(${[
  quote(city.cityId),
  quote("GB"),
  quote(city.cityName),
  quote(city.cityAscii),
  quote(city.adminName),
  numberOrNull(city.latitude),
  numberOrNull(city.longitude),
  String(city.population),
].join(", ")})`).join(",\n");

const migration = `-- Generated by scripts/generate-uk-city-seed.mjs from world-cities-json 1.0.1.
-- Source: SimpleMaps World Cities Database; license: CC BY 4.0.
-- Regenerate rather than editing these records by hand.
insert into public.supported_cities (
  city_id, country_code, city_name, city_ascii, admin_name, latitude, longitude, population
)
values
${valueRows}
on conflict (city_id) do update
set city_name = excluded.city_name,
    city_ascii = excluded.city_ascii,
    admin_name = excluded.admin_name,
    latitude = excluded.latitude,
    longitude = excluded.longitude,
    population = excluded.population;
`;

mkdirSync(dirname(migrationPath), { recursive: true });
writeFileSync(migrationPath, migration, "utf8");
console.log(`Generated ${ukCities.length} UK locations (${Buffer.byteLength(migration)} bytes of SQL).`);